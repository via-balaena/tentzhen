//! Makes the verifier's test quotes from swtpm, a software TPM, and writes them to
//! `firmware/verifier/tests/swtpm_quotes.txt`:
//!
//! ```text
//! cargo run -p tentzhen-verifier --example swtpm_quotes -- <an empty scratch directory>
//! ```
//!
//! It needs `swtpm` on the PATH (Homebrew's swtpm 0.10.2 made the committed file). It writes each
//! TPM command byte by byte and reads each response the same way, refusing any response code but
//! success, so the test inputs do not come from the parser they test (`tpm2-protocol`, in the
//! verifier).
//! The quotes differ on every run (each TPM's keys are new, and ECDSA signatures are random), so
//! the committed file is kept, not regenerated by the Quality Gate.
//!
//! What it makes, all from TPM A unless named:
//! - `ak_a`: TPM A's attestation key, a restricted ECDSA P-256 signing key made as a primary in the
//!   endorsement hierarchy, as SEC1 x || y;
//! - `out`: a quote of PCRs 0 to 10 at check-out, after one extend into each;
//! - `in`: a quote of the same PCRs in the same boot, with a new challenge;
//! - `extended`: one more extend into PCR 9, then a quote, still in the same boot;
//! - `restarted`: swtpm stopped and started again on the same state (a TPM Reset), the key made
//!   again from the same template, the same extends, and a quote;
//! - `eight`: a quote of PCRs 0 to 7 only, in the same boot as `extended`;
//! - `sha1`: a quote of the SHA-1 bank's PCRs 0 to 10, and `two`: of both banks' PCRs 0 to 10,
//!   each kept with the SHA-256 values, as a hub would pass them on;
//! - `ak_b` and `other`: TPM B's key, and its quote of PCRs 0 to 10 with `in`'s challenge.
//!
//! Each quote has its challenge, the TPMS_ATTEST the TPM signed, the TPMT_SIGNATURE, and the
//! SHA-256 values of the PCRs it covers, as PCR_Read returned them (PCRs 0 to 10 for `sha1` and
//! `two`).

use std::fmt::Write as _;
use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::process::{Child, Command};
use std::thread::sleep;
use std::time::Duration;

const ST_NO_SESSIONS: u16 = 0x8001;
const ST_SESSIONS: u16 = 0x8002;
const RS_PW: u32 = 0x4000_0009;
const RH_ENDORSEMENT: u32 = 0x4000_000B;
const CC_CREATE_PRIMARY: u32 = 0x0000_0131;
const CC_PCR_EXTEND: u32 = 0x0000_0182;
const CC_PCR_READ: u32 = 0x0000_017E;
const CC_QUOTE: u32 = 0x0000_0158;
const ALG_ECC: u16 = 0x0023;
const ALG_SHA1: u16 = 0x0004;
const ALG_SHA256: u16 = 0x000B;
const ALG_NULL: u16 = 0x0010;
const ALG_ECDSA: u16 = 0x0018;
const ECC_NIST_P256: u16 = 0x0003;
/// fixedTPM, fixedParent, sensitiveDataOrigin, userWithAuth, restricted, sign.
const AK_ATTRIBUTES: u32 = (1 << 1) | (1 << 4) | (1 << 5) | (1 << 6) | (1 << 16) | (1 << 18);

struct Swtpm {
    child: Child,
    port: u16,
}

impl Swtpm {
    fn start(state: &Path, port: u16) -> Swtpm {
        std::fs::create_dir_all(state).unwrap();
        let child = Command::new("swtpm")
            .args(["socket", "--tpm2", "--tpmstate"])
            .arg(format!("dir={}", state.display()))
            .args(["--server", &format!("type=tcp,port={port}")])
            .args(["--ctrl", &format!("type=tcp,port={}", port + 1)])
            .args(["--flags", "not-need-init,startup-clear"])
            .spawn()
            .expect("swtpm is on the PATH");
        let tpm = Swtpm { child, port };
        for _ in 0..50 {
            if TcpStream::connect(("127.0.0.1", port)).is_ok() {
                return tpm;
            }
            sleep(Duration::from_millis(100));
        }
        tpm.stop();
        panic!("swtpm did not open port {port}");
    }

    fn stop(mut self) {
        self.child.kill().unwrap();
        self.child.wait().unwrap();
    }

    /// Sends one command and returns the response after its 10-byte header, refusing any
    /// response code but success.
    fn send(&self, command: &[u8]) -> Vec<u8> {
        let mut s = TcpStream::connect(("127.0.0.1", self.port)).unwrap();
        s.write_all(command).unwrap();
        let mut header = [0u8; 10];
        s.read_exact(&mut header).unwrap();
        let size = u32::from_be_bytes(header[2..6].try_into().unwrap()) as usize;
        let rc = u32::from_be_bytes(header[6..10].try_into().unwrap());
        let mut body = vec![0u8; size - 10];
        s.read_exact(&mut body).unwrap();
        assert_eq!(
            rc,
            0,
            "TPM response code {rc:#x} to command {:02x?}",
            &command[6..10]
        );
        body
    }
}

fn u16b(v: &mut Vec<u8>, x: u16) {
    v.extend_from_slice(&x.to_be_bytes());
}
fn u32b(v: &mut Vec<u8>, x: u32) {
    v.extend_from_slice(&x.to_be_bytes());
}
fn tpm2b(v: &mut Vec<u8>, bytes: &[u8]) {
    u16b(v, bytes.len() as u16);
    v.extend_from_slice(bytes);
}

/// A command: header, handles, then the password session (empty auth) if `sessions`, then the
/// parameters.
fn command(cc: u32, handles: &[u32], sessions: bool, parameters: &[u8]) -> Vec<u8> {
    let mut v = Vec::new();
    u16b(
        &mut v,
        if sessions {
            ST_SESSIONS
        } else {
            ST_NO_SESSIONS
        },
    );
    u32b(&mut v, 0);
    u32b(&mut v, cc);
    for h in handles {
        u32b(&mut v, *h);
    }
    if sessions {
        let mut auth = Vec::new();
        u32b(&mut auth, RS_PW);
        tpm2b(&mut auth, &[]);
        auth.push(0);
        tpm2b(&mut auth, &[]);
        u32b(&mut v, auth.len() as u32);
        v.extend_from_slice(&auth);
    }
    v.extend_from_slice(parameters);
    let size = v.len() as u32;
    v[2..6].copy_from_slice(&size.to_be_bytes());
    v
}

/// A TPML_PCR_SELECTION of PCRs 0 to `last` in each of `banks`.
fn selection(banks: &[u16], last: u32) -> Vec<u8> {
    let mut select = [0u8; 3];
    for pcr in 0..=last {
        select[(pcr / 8) as usize] |= 1 << (pcr % 8);
    }
    let mut v = Vec::new();
    u32b(&mut v, banks.len() as u32);
    for bank in banks {
        u16b(&mut v, *bank);
        v.push(3);
        v.extend_from_slice(&select);
    }
    v
}

struct Reader<'a>(&'a [u8]);
impl<'a> Reader<'a> {
    fn take(&mut self, n: usize) -> &'a [u8] {
        let (head, tail) = self.0.split_at(n);
        self.0 = tail;
        head
    }
    fn u16(&mut self) -> u16 {
        u16::from_be_bytes(self.take(2).try_into().unwrap())
    }
    fn u32(&mut self) -> u32 {
        u32::from_be_bytes(self.take(4).try_into().unwrap())
    }
    fn tpm2b(&mut self) -> &'a [u8] {
        let n = self.u16() as usize;
        self.take(n)
    }
}

/// Makes the attestation key and returns its handle and its public point, x || y.
fn create_ak(tpm: &Swtpm) -> (u32, Vec<u8>) {
    let mut public = Vec::new();
    u16b(&mut public, ALG_ECC);
    u16b(&mut public, ALG_SHA256);
    u32b(&mut public, AK_ATTRIBUTES);
    tpm2b(&mut public, &[]); // authPolicy
    u16b(&mut public, ALG_NULL); // symmetric
    u16b(&mut public, ALG_ECDSA); // scheme
    u16b(&mut public, ALG_SHA256);
    u16b(&mut public, ECC_NIST_P256);
    u16b(&mut public, ALG_NULL); // kdf
    tpm2b(&mut public, &[]); // unique.x
    tpm2b(&mut public, &[]); // unique.y
    let mut p = Vec::new();
    tpm2b(&mut p, &[0, 0, 0, 0]); // inSensitive: empty userAuth and data
    tpm2b(&mut p, &public);
    tpm2b(&mut p, &[]); // outsideInfo
    u32b(&mut p, 0); // creationPCR: none
    let body = tpm.send(&command(CC_CREATE_PRIMARY, &[RH_ENDORSEMENT], true, &p));
    let mut r = Reader(&body);
    let handle = r.u32();
    let _parameter_size = r.u32();
    let out_public = r.tpm2b();
    let mut t = Reader(out_public);
    assert_eq!(t.u16(), ALG_ECC);
    assert_eq!(t.u16(), ALG_SHA256);
    assert_eq!(t.u32(), AK_ATTRIBUTES);
    t.tpm2b();
    assert_eq!(t.u16(), ALG_NULL);
    assert_eq!(t.u16(), ALG_ECDSA);
    assert_eq!(t.u16(), ALG_SHA256);
    assert_eq!(t.u16(), ECC_NIST_P256);
    assert_eq!(t.u16(), ALG_NULL);
    let x = t.tpm2b().to_vec();
    let y = t.tpm2b().to_vec();
    assert_eq!((x.len(), y.len()), (32, 32));
    (handle, [x, y].concat())
}

fn extend(tpm: &Swtpm, pcr: u32, digest: [u8; 32]) {
    let mut p = Vec::new();
    u32b(&mut p, 1);
    u16b(&mut p, ALG_SHA256);
    p.extend_from_slice(&digest);
    tpm.send(&command(CC_PCR_EXTEND, &[pcr], true, &p));
}

/// One extend into each of PCRs 0 to 10, each with its own digest.
fn boot(tpm: &Swtpm) {
    for pcr in 0..=10 {
        extend(tpm, pcr, [0xB0 + pcr as u8; 32]);
    }
}

/// The values of PCRs 0 to `last`, read eight at a time, as PCR_Read returns at most eight.
fn read_pcrs(tpm: &Swtpm, last: u32) -> Vec<[u8; 32]> {
    let mut values = Vec::new();
    let mut first = 0;
    while first <= last {
        let upto = (first + 7).min(last);
        let mut select = [0u8; 3];
        for pcr in first..=upto {
            select[(pcr / 8) as usize] |= 1 << (pcr % 8);
        }
        let mut p = Vec::new();
        u32b(&mut p, 1);
        u16b(&mut p, ALG_SHA256);
        p.push(3);
        p.extend_from_slice(&select);
        let body = tpm.send(&command(CC_PCR_READ, &[], false, &p));
        let mut r = Reader(&body);
        let _update_counter = r.u32();
        assert_eq!(r.u32(), 1);
        assert_eq!(r.u16(), ALG_SHA256);
        let n = r.take(1)[0] as usize;
        assert_eq!(
            r.take(n),
            &select[..n],
            "PCR_Read returned the selection asked for"
        );
        let count = r.u32();
        assert_eq!(count, upto - first + 1);
        for _ in 0..count {
            values.push(r.tpm2b().try_into().unwrap());
        }
        first = upto + 1;
    }
    values
}

struct Quote {
    challenge: [u8; 32],
    attest: Vec<u8>,
    signature: Vec<u8>,
    pcrs: Vec<[u8; 32]>,
}

fn quote(tpm: &Swtpm, ak: u32, challenge: [u8; 32], last: u32) -> Quote {
    quote_banks(tpm, ak, challenge, &[ALG_SHA256], last)
}

fn quote_banks(tpm: &Swtpm, ak: u32, challenge: [u8; 32], banks: &[u16], last: u32) -> Quote {
    let mut p = Vec::new();
    tpm2b(&mut p, &challenge);
    u16b(&mut p, ALG_ECDSA);
    u16b(&mut p, ALG_SHA256);
    p.extend_from_slice(&selection(banks, last));
    let body = tpm.send(&command(CC_QUOTE, &[ak], true, &p));
    let mut r = Reader(&body);
    let parameter_size = r.u32() as usize;
    let mut params = Reader(r.take(parameter_size));
    let attest = params.tpm2b().to_vec();
    let signature = params.0.to_vec();
    Quote {
        challenge,
        attest,
        signature,
        pcrs: read_pcrs(tpm, last),
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::new(), |mut s, b| {
        write!(s, "{b:02x}").unwrap();
        s
    })
}

fn main() {
    let scratch = PathBuf::from(std::env::args().nth(1).expect("a scratch directory"));
    assert!(
        !scratch.exists() || std::fs::read_dir(&scratch).unwrap().next().is_none(),
        "the scratch directory is empty"
    );
    let state_a = scratch.join("tpm-a");
    let state_b = scratch.join("tpm-b");

    let tpm = Swtpm::start(&state_a, 23210);
    let (ak, ak_a) = create_ak(&tpm);
    boot(&tpm);
    let out = quote(&tpm, ak, [0x01; 32], 10);
    let in_ = quote(&tpm, ak, [0x02; 32], 10);
    extend(&tpm, 9, [0xEE; 32]);
    let extended = quote(&tpm, ak, [0x03; 32], 10);
    let eight = quote(&tpm, ak, [0x04; 32], 7);
    let sha1 = quote_banks(&tpm, ak, [0x06; 32], &[ALG_SHA1], 10);
    let two = quote_banks(&tpm, ak, [0x07; 32], &[ALG_SHA256, ALG_SHA1], 10);
    tpm.stop();

    let tpm = Swtpm::start(&state_a, 23210);
    let (ak, again) = create_ak(&tpm);
    assert_eq!(
        again, ak_a,
        "the same template under the same seed makes the same key"
    );
    boot(&tpm);
    let restarted = quote(&tpm, ak, [0x05; 32], 10);
    tpm.stop();

    let tpm = Swtpm::start(&state_b, 23220);
    let (ak, ak_b) = create_ak(&tpm);
    boot(&tpm);
    let other = quote(&tpm, ak, [0x02; 32], 10);
    tpm.stop();

    let mut text = String::from(
        "# Made by `cargo run -p tentzhen-verifier --example swtpm_quotes`, from swtpm 0.10.2.\n\
         # One `name = hex` per line; see that example for what each quote is.\n",
    );
    writeln!(text, "ak_a = {}", hex(&ak_a)).unwrap();
    writeln!(text, "ak_b = {}", hex(&ak_b)).unwrap();
    for (name, q) in [
        ("out", &out),
        ("in", &in_),
        ("extended", &extended),
        ("restarted", &restarted),
        ("eight", &eight),
        ("sha1", &sha1),
        ("two", &two),
        ("other", &other),
    ] {
        writeln!(text, "{name}.challenge = {}", hex(&q.challenge)).unwrap();
        writeln!(text, "{name}.attest = {}", hex(&q.attest)).unwrap();
        writeln!(text, "{name}.signature = {}", hex(&q.signature)).unwrap();
        writeln!(text, "{name}.pcrs = {}", hex(&q.pcrs.concat())).unwrap();
    }
    let at = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/swtpm_quotes.txt");
    std::fs::write(&at, text).unwrap();
    println!("wrote {}", at.display());
}
